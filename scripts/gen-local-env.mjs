// Writes the root .env for LOCAL docker testing from `supabase status -o env`
// (piped on stdin). Keeps the dockerized backend's keys in sync with the app.
//   usage:  supabase status -o env | node scripts/gen-local-env.mjs
import { writeFileSync, readFileSync } from "node:fs"
import { randomBytes } from "node:crypto"

const input = readFileSync(0, "utf8") // stdin
const map = {}
for (const line of input.split("\n")) {
  const m = line.match(/^([A-Z0-9_]+)=["']?(.*?)["']?\s*$/)
  if (m) map[m[1]] = m[2]
}

const api = map.API_URL || map.SUPABASE_URL || "http://localhost:54321"
const anon = map.ANON_KEY || map.SUPABASE_ANON_KEY || map.PUBLISHABLE_KEY
const service = map.SERVICE_ROLE_KEY || map.SUPABASE_SERVICE_ROLE_KEY || map.SECRET_KEY
const db = map.DB_URL || "postgresql://postgres:postgres@localhost:54322/postgres"

if (!anon || !service) {
  console.error("✗ Couldn't read ANON/SERVICE keys from `supabase status -o env`. Is the backend up? Run `make backend` first.")
  process.exit(1)
}

// Always overwrite: for a local stack .env must track the RUNNING backend's
// URL+keys, or the app silently builds against a stale/hosted project. The file
// is gitignored and only holds local-dev values, so regenerating is safe.

const env = `# Generated by \`make env\` for LOCAL docker testing — DO NOT COMMIT.
# Supabase (local dockerized backend)
NEXT_PUBLIC_SUPABASE_URL=${api}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}
SUPABASE_SERVICE_ROLE_KEY=${service}
DATABASE_URL=${db}

# Cache (host-networked redis container)
REDIS_URL=redis://localhost:6379

# App
APP_DOMAIN=localhost
NEXT_PUBLIC_APP_URL=http://localhost:3000
CRON_SECRET=${randomBytes(24).toString("hex")}

# Integrations — placeholders locally (M-Pesa/SMS/email not exercised on localhost)
MPESA_CONSUMER_KEY=xxx
MPESA_CONSUMER_SECRET=xxx
MPESA_SHORTCODE=174379
MPESA_PASSKEY=xxx
MPESA_CALLBACK_URL=http://localhost:3000/api/payments/mpesa/callback
`

writeFileSync(".env", env)
console.error(`✓ Wrote .env pointing at ${api}`)
